#pragma once

#include <opencv2/objdetect/charuco_detector.hpp>
#include <optional>
#include <string>

#include "camera_cal/calibrator.hpp"

namespace camera_cal {

/// @brief Calibrator for a ChArUco target (chessboard with ArUco markers in the
///        white squares).  Unlike a chessboard, partially visible boards are
///        still usable, since each corner is identified by its neighbouring markers.
class CharucoCalibrator : public CameraCalibrator {
   public:
    struct Config {
        /// Number of square rows on the calibration board
        int rows{ 0 };
        /// Number of square columns on the calibration board
        int cols{ 0 };
        /// Physical side length of one square in metres
        double square_size_m{ 0.0 };
        /// Physical side length of one ArUco marker in metres
        double marker_size_m{ 0.0 };
        /// Predefined ArUco dictionary name, e.g. "DICT_5X5_100"
        std::string aruco_dict;
        /// Board uses the layout generated by OpenCV < 4.6 (differs for even row counts)
        bool legacy_pattern{ false };
    };

    /// @brief Check that @p config describes a usable board.
    /// @return An error message, or std::nullopt if the config is valid
    static std::optional<std::string> validate(const Config& config);

    /// @throws std::invalid_argument if @p config fails validate()
    explicit CharucoCalibrator(const Config& config);

   protected:
    bool detect(const cv::Mat& detect_image, const cv::Mat& full_image, double scale, cv::Mat& debug,
                Detection& out) override;

   private:
    Config config_;
    cv::aruco::CharucoBoard board_;
    cv::aruco::CharucoDetector detector_;
};

}  // namespace camera_cal
